import 'dart:math';

import 'package:flutter_test/flutter_test.dart';
import 'package:tg_media_probe/security/tdlib_key.dart';

void main() {
  group('TdlibDatabaseKey', () {
    test('generates 64 lowercase hex characters', () async {
      final store = MemorySecretStore();
      final key = await TdlibDatabaseKey(store: store).obtain();

      expect(key.length, TdlibDatabaseKey.keyHexLength);
      expect(RegExp(r'^[0-9a-f]{64}$').hasMatch(key), isTrue,
          reason: 'key must be pure lowercase hex, got "$key"');
      expect(TdlibDatabaseKey.isValid(key), isTrue);
    });

    test('persists the key so a restart opens the same database', () async {
      final store = MemorySecretStore();
      final first = await TdlibDatabaseKey(store: store).obtain();
      final second = await TdlibDatabaseKey(store: store).obtain();

      expect(second, first,
          reason: 'a regenerated key would make the existing database '
              'unreadable');
      expect(await store.read(TdlibDatabaseKey.keyName), first);
    });

    test('two fresh installs get different keys', () async {
      final a = await TdlibDatabaseKey(store: MemorySecretStore()).obtain();
      final b = await TdlibDatabaseKey(store: MemorySecretStore()).obtain();

      expect(a, isNot(b), reason: 'a fixed key would be shipped in the app');
    });

    test('a malformed stored key raises instead of being overwritten',
        () async {
      final store = MemorySecretStore(
          <String, String>{TdlibDatabaseKey.keyName: 'deadbeef'});

      await expectLater(
        TdlibDatabaseKey(store: store).obtain(),
        throwsA(isA<TdlibKeyException>()),
      );
      expect(await store.read(TdlibDatabaseKey.keyName), 'deadbeef',
          reason: 'the old value may still open an existing database');
    });

    test('never hands TDLib an empty key', () async {
      final key = await TdlibDatabaseKey(store: MemorySecretStore()).obtain();
      expect(key, isNotEmpty);
      expect(key.trim(), key);
    });

    test('peek does not create a key', () async {
      final store = MemorySecretStore();
      expect(await TdlibDatabaseKey(store: store).peek(), isNull);
      expect(await store.read(TdlibDatabaseKey.keyName), isNull);
    });

    test('peek returns the key once one exists', () async {
      final store = MemorySecretStore();
      final created = await TdlibDatabaseKey(store: store).obtain();
      expect(await TdlibDatabaseKey(store: store).peek(), created);
    });

    test('generated bytes use the injected random source', () {
      final key = TdlibDatabaseKey(store: MemorySecretStore(), random: Random(7))
          .generate();
      final again = TdlibDatabaseKey(store: MemorySecretStore(), random: Random(7))
          .generate();

      expect(key, again, reason: 'same seed must give the same key');
      expect(TdlibDatabaseKey.isValid(key), isTrue);
    });

    test('mask keeps only the ends', () {
      const key =
          '0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef';
      final masked = TdlibDatabaseKey.mask(key);

      expect(masked.startsWith('012345'), isTrue);
      expect(masked.endsWith('cdef'), isTrue);
      expect(masked.contains('0123456789abcdef'), isFalse);
      expect(masked.length, lessThan(key.length));
    });

    test('mask hides very short values completely', () {
      expect(TdlibDatabaseKey.mask('short'), '***');
    });

    test('isValid rejects uppercase, wrong length and non-hex', () {
      expect(TdlibDatabaseKey.isValid('A' * 64), isFalse);
      expect(TdlibDatabaseKey.isValid('a' * 63), isFalse);
      expect(TdlibDatabaseKey.isValid('a' * 65), isFalse);
      expect(TdlibDatabaseKey.isValid('${'a' * 63}z'), isFalse);
      expect(TdlibDatabaseKey.isValid(''), isFalse);
    });
  });
}
